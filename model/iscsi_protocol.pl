% Layer 2c: Default-value conformance  (RFC 3720 Section 12)
%
% The assumed-if-absent default of each key. Most match; InitialR2T does not
% (RFC Yes vs impl No) -> deviation D4.
% ===========================================================================

% default_case(Key, ImplDefault, RfcDefault, Section)
default_case('InitialR2T',      no,     yes,    '12.10').
default_case('ImmediateData',   yes,    yes,    '12.11').
default_case('MaxBurstLength',  262144, 262144, '12.13').
default_case('FirstBurstLength',65536,  65536,  '12.14').
default_case('DataPDUInOrder',  yes,    yes,    '12.18').
default_case('ErrorRecoveryLevel', 0,   0,      '12.20').

emit_default :-
    forall(default_case(Key, ImplD, RfcD, Sec),
           ( ( ImplD == RfcD -> Status = conform ; dev_status('D4', Status) ),
             token(ImplD, ITok), token(RfcD, RTok),
             format("DEFAULT key=~w impl_default=~w rfc_default=~w section=~w status=~w~n",
                    [Key, ITok, RTok, Sec, Status]) )).

% ===========================================================================
% Layer 3: Login state machine  (RFC 3720 Section 5.3)
%
% A single login step from Free with AuthMethod=None negotiated through. The
% resulting phase is a function of the PDU's CSG/NSG/Transit per the RFC stage
% codes (0=SecurityNegotiation, 1=LoginOperationalNegotiation,
% 3=FullFeaturePhase). Illegal initial CSG (2,3) => login fails.
% ===========================================================================

next_state(0, NSG, 1, 'LoginOperationalNegotiation') :- NSG =:= 1, !.
next_state(0, NSG, 1, 'FullFeaturePhase')            :- NSG =:= 3, !.
next_state(0, _,   _, 'SecurityNegotiation')         :- !.
next_state(1, NSG, 1, 'FullFeaturePhase')            :- NSG =:= 3, !.
next_state(1, _,   _, 'LoginOperationalNegotiation') :- !.
next_state(_, _, _, 'Failed').

emit_state :-
    forall(( between(0, 3, CSG), between(0, 3, NSG), member(T, [0, 1]) ),
           ( next_state(CSG, NSG, T, State),
             format("STATE csg=~w nsg=~w transit=~w expect=~w~n",
                    [CSG, NSG, T, State]) )).

% ===========================================================================
% Layer 4: CHAP message ordering  (RFC 3720 Section 11; RFC 1994)
%
% Legal ordering: AuthMethod=CHAP -> CHAP_A -> {CHAP_I,CHAP_C} ->
% {CHAP_N,CHAP_R} -> success. Sending CHAP_N/CHAP_R before any CHAP_A, or
% refusing CHAP when the target requires it, is a violation -> login fails.
% ===========================================================================

chap_case(offer_chap,
          ['AuthMethod'-'CHAP'],
          'SecurityNegotiation', 'AuthMethod'-'CHAP').
chap_case(send_chap_a,
          ['CHAP_A'-'5'],
          'SecurityNegotiation', 'CHAP_C'-none).
chap_case(out_of_order,
          ['CHAP_N'-user, 'CHAP_R'-'0xab'],
          'Failed', none).
chap_case(refuse_chap,
          ['AuthMethod'-'None'],
          'Failed', none).

emit_chap :-
    forall(chap_case(Name, Params, State, Key),
           ( params_field(Params, ParamsField),
             key_field(Key, KeyField),
             format("CHAP case=~w params=~w expect_state=~w expect_key=~w~n",
                    [Name, ParamsField, State, KeyField]) )).

params_field([], '-').
params_field([K-V|Rest], Field) :-
    pair_tok(K, V, First),
    params_field_rest(Rest, First, Field).
params_field_rest([], Acc, Acc).
params_field_rest([K-V|Rest], Acc, Field) :-
    pair_tok(K, V, P),
    atomic_list_concat([Acc, ',', P], Acc1),
    params_field_rest(Rest, Acc1, Field).
pair_tok(K, V, Tok) :- atomic_list_concat([K, ':', V], Tok).

key_field(none, none) :- !.
key_field(K-none, K) :- !.
key_field(K-V, Field) :- atomic_list_concat([K, '=', V], Field).

% ===========================================================================
% atomic_list_concat/2 (Scryer has no builtin): concatenate atoms.
% ===========================================================================

atomic_list_concat(List, Atom) :-
    phrase(concat_atoms(List), Codes),
    atom_codes(Atom, Codes).

concat_atoms([]) --> [].
concat_atoms([A|As]) -->
    { ( atom(A) -> atom_codes(A, Cs) ; number_codes(A, Cs) ) },
    seq_codes(Cs), concat_atoms(As).

seq_codes([]) --> [].
seq_codes([C|Cs]) --> [C], seq_codes(Cs).
