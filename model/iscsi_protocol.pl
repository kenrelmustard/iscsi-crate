% ===========================================================================
% Layer 1: Command-sequence-number window  (RFC 3720 3.2.2.1; RFC 1982)
%
% A CmdSN is in-window iff the signed 32-bit forward distance from ExpCmdSN is
% >= 0 and the signed forward distance to MaxCmdSN is >= 0. This is pure
% serial-number arithmetic from the RFC; it does not reference the code.
% ===========================================================================

signed32(U, S) :- ( U >= 2147483648 -> S is U - 4294967296 ; S = U ).
wrap_sub(A, B, D) :- D is (A - B) mod 4294967296.

sn_in_window(Sn, Exp, Max) :-
    wrap_sub(Sn, Exp, DiffExpU), signed32(DiffExpU, DiffExp),
    wrap_sub(Max, Sn, DiffMaxU), signed32(DiffMaxU, DiffMax),
    DiffExp >= 0, DiffMax >= 0.

window_expect(Sn, Exp, Max, accept) :- sn_in_window(Sn, Exp, Max), !.
window_expect(_, _, _, reject).

