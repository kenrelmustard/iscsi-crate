% ===========================================================================
% Layer 2: Login key negotiation result-functions  (RFC 3720 Section 12)
%
% For each case we compute the RFC-correct result of combining the target's
% current value with the initiator's offer, AND what the implementation
% actually produces, then mark the row conform or deviation. The Rust test
% sets the target value explicitly so the *result function* itself is tested,
% not just behaviour at the default.
% ===========================================================================

