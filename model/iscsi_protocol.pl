%% iscsi_protocol.pl
%%
%% A declarative model of the parts of the iSCSI protocol (RFC 3720) whose
%% behaviour is *logical* rather than wire-format: the login state machine,
%% login key negotiation result-functions, command-sequence-number windowing,
%% and CHAP message ordering.
%%
%% This model is the source of truth for a generated test corpus. Running
%% `?- emit_corpus.` (see Makefile target `corpus`) prints a line-oriented
%% corpus to stdout; the Rust integration test `tests/model_corpus_tests.rs`
%% replays that corpus against the real implementation and asserts the
%% implementation agrees with the model. Divergences mean either the model or
%% the implementation is wrong -- which is exactly what we want to surface.
%%
%% Tested with Scryer Prolog. Pure ISO + library(format)/lists/between.
%%
%% Scope note: this models the protocol *logic*, not PDU byte encoding, SCSI
%% block I/O, or socket/async behaviour. Those are serialization / I/O concerns
%% better covered by the crate's existing Rust tests.

:- use_module(library(format)).
:- use_module(library(lists)).
:- use_module(library(between)).

% forall/2 is not a Scryer builtin; define the standard meta-predicate.
forall(Cond, Action) :- \+ ( Cond, \+ Action ).

% ===========================================================================
% Entry point
% ===========================================================================

emit_corpus :-
    format("# iSCSI protocol model corpus~n", []),
    format("# GENERATED by model/iscsi_protocol.pl -- do not edit by hand.~n", []),
    format("# Regenerate with: make -C model corpus~n", []),
    format("#~n", []),
    format("# Columns are KIND key=value ...  (see model/README.md)~n", []),
    emit_seqwindow,
    emit_negotiate,
    emit_state,
    emit_chap.

% ===========================================================================
% Layer 1: Command-sequence-number window  (RFC 3720 Section 3.2.2.1)
%
% Models SessionData::validate_cmd_sn / sn_in_window in
% src/typestate_session.rs. The window [ExpCmdSN, MaxCmdSN] is compared using
% 32-bit serial-number arithmetic: a number is in-window iff the forward
% distance from ExpCmdSN is non-negative AND the forward distance to MaxCmdSN
% is non-negative, where "forward distance" is the signed interpretation of
% the 32-bit wrapping difference (the i32 cast in the Rust code).
% ===========================================================================

u32(X) :- X >= 0, X < 4294967296.

% signed32(+Unsigned32, -Signed): two's-complement reinterpretation.
signed32(U, S) :-
    ( U >= 2147483648 -> S is U - 4294967296 ; S = U ).

% wrap_sub(+A, +B, -D): (A - B) mod 2^32.
wrap_sub(A, B, D) :- D is (A - B) mod 4294967296.

% sn_in_window(+Sn, +Exp, +Max): mirrors the Rust sn_in_window helper.
sn_in_window(Sn, Exp, Max) :-
    wrap_sub(Sn, Exp, DiffExpU), signed32(DiffExpU, DiffExp),
    wrap_sub(Max, Sn, DiffMaxU), signed32(DiffMaxU, DiffMax),
    DiffExp >= 0, DiffMax >= 0.

window_expect(Sn, Exp, Max, accept) :- sn_in_window(Sn, Exp, Max), !.
window_expect(_, _, _, reject).

% Test points: small windows, boundary, and 32-bit wrap-around.
seqwindow_case(1,          1,          0).
seqwindow_case(1,          1,          1).
seqwindow_case(1,          1,          2).
seqwindow_case(1,          3,          0).
seqwindow_case(1,          3,          1).
seqwindow_case(1,          3,          2).
seqwindow_case(1,          3,          3).
seqwindow_case(1,          3,          4).
seqwindow_case(5,          5,          4).
seqwindow_case(5,          5,          5).
seqwindow_case(5,          5,          6).
seqwindow_case(10,         20,         9).
seqwindow_case(10,         20,         10).
seqwindow_case(10,         20,         15).
seqwindow_case(10,         20,         20).
seqwindow_case(10,         20,         21).
% Wrap-around window [0xFFFFFFFE, 0x00000001]
seqwindow_case(4294967294, 1,          4294967293).
seqwindow_case(4294967294, 1,          4294967294).
