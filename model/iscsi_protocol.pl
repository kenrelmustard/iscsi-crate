%% iscsi_protocol.pl
%%
%% An executable model of the *logical* layers of the iSCSI protocol, derived
%% from RFC 3720 (and RFC 1994 for CHAP, RFC 1982 for serial-number
%% arithmetic) -- NOT from the Rust implementation. The rules below encode
%% what the RFC says; the Rust integration test then checks the implementation
%% against this independent oracle.
%%
%% Why derive from the RFC and not the code: the implementation (and its own
%% unit tests) can share the same misreading of the spec. A model that merely
%% restates the code is a tautology. So each negotiation rule cites its RFC
%% section, and every place the implementation deliberately or accidentally
%% diverges is recorded in an explicit deviation/5 registry rather than baked
%% in silently.
%%
%% RFC 3720 Section 12 result functions used here (verified against the spec
%% and the UNH-IOL iSCSI test suite):
%%   HeaderDigest/DataDigest 12.1  : list selection (None | CRC32C), default None
%%   InitialR2T              12.10 : boolean OR,  default Yes
%%   ImmediateData           12.11 : boolean AND, default Yes
%%   MaxRecvDataSegmentLength 12.12: declarative, default 8192
%%   MaxBurstLength          12.13 : Minimum, default 262144
%%   FirstBurstLength        12.14 : Minimum, default 65536; MUST NOT exceed MaxBurstLength
%%   DefaultTime2Wait        12.15 : Maximum, default 2
%%   DefaultTime2Retain      12.16 : Minimum, default 20
%%   MaxOutstandingR2T       12.17 : Minimum, default 1
%%   DataPDUInOrder          12.18 : boolean OR,  default Yes
%%   DataSequenceInOrder     12.19 : boolean OR,  default Yes
%%   ErrorRecoveryLevel      12.20 : Minimum, default 0
%%
%% Tested with Scryer Prolog. Regenerate the corpus with: make -C model corpus

